/** Local-only control boundaries. Credentials never enter persistent storage. */
const encoder = new TextEncoder();
export const MAX_TEXT_BYTES = 16_384;
export const ECHO_PREFIX = 'Echo: ';
/** Agent chat may include the complete request plus the fixed echo prefix. */
export const MAX_REPLY_BYTES = MAX_TEXT_BYTES + encoder.encode(ECHO_PREFIX).byteLength;
export const MAX_LOG_ENTRIES = 100;
const ROOM_NAME = /^lab-[a-z0-9][a-z0-9-]{0,47}$/;
const IDENTITY = /^(browser|smoke)-[a-z0-9][a-z0-9-]{0,47}$/;

export type LabState = 'disconnected' | 'connecting' | 'connected' | 'reconnecting' | 'disconnecting' | 'error';
export type EntryKind = 'system' | 'sent' | 'received' | 'diagnostic' | 'error';
export interface Entry { kind: EntryKind; text: string; time: string }
export interface SessionRequest { room: string; identity: string; dispatch_agent: boolean }
export interface SessionResponse {
  url: string;
  token: string;
  room: string;
  identity: string;
  expires_in: number;
  agent_name: string;
  agent_dispatched: boolean;
}
export interface RoomCallbacks {
  onText(text: string): void;
  onDiagnostic(text: string): void;
  onDisconnected(): void;
  onReconnecting(): void;
  onReconnected(): void;
}
export interface RoomPort {
  connect(url: string, token: string): Promise<void>;
  disconnect(): Promise<void>;
  sendText(text: string): Promise<void>;
  setMicrophoneEnabled(enabled: boolean): Promise<void>;
}
export interface LabCallbacks {
  onState(state: LabState): void;
  onEntry(kind: EntryKind, text: string): void;
  onMicrophone(enabled: boolean): void;
}
export class LabInputError extends Error {}

export function validateSession(request: SessionRequest, accessToken: string): void {
  if (!ROOM_NAME.test(request.room)) {
    throw new LabInputError('Use a room beginning lab- with lowercase letters, numbers or hyphens.');
  }
  if (!IDENTITY.test(request.identity)) throw new LabInputError('The local participant identity is invalid.');
  if (accessToken.length < 16 || accessToken.length > 512 || /\s/.test(accessToken)) {
    throw new LabInputError('Enter the local access token generated by local setup.');
  }
}

export function validateMessage(input: string): string {
  const text = input.trim();
  if (!text) throw new LabInputError('Enter a message first.');
  if (encoder.encode(text).byteLength > MAX_TEXT_BYTES) {
    throw new LabInputError('Messages must be at most 16 KiB of UTF-8 text.');
  }
  return text;
}

export function appendBounded<T>(items: readonly T[], value: T, limit = MAX_LOG_ENTRIES): T[] {
  if (!Number.isInteger(limit) || limit < 1) throw new RangeError('A positive entry limit is required.');
  return [...items, value].slice(-limit);
}

/** Reads SDK text incrementally; oversize streams are closed by async-iterator return. */
export async function readBoundedText(stream: AsyncIterable<string>, limit = MAX_TEXT_BYTES): Promise<string> {
  let bytes = 0;
  const chunks: string[] = [];
  for await (const chunk of stream) {
    bytes += encoder.encode(chunk).byteLength;
    if (bytes > limit) throw new LabInputError('An incoming stream exceeded the local text limit.');
    chunks.push(chunk);
  }
  return chunks.join('');
}

export async function boundedResponse(response: Response): Promise<unknown> {
  if (!response.body) throw new Error('The local API returned an empty response.');
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let bytes = 0;
  let body = '';
  try {
    while (true) {
      const part = await reader.read();
      if (part.done) break;
      bytes += part.value.byteLength;
      if (bytes > MAX_TEXT_BYTES) throw new Error('The local API returned an oversized response.');
      body += decoder.decode(part.value, { stream: true });
    }
    body += decoder.decode();
    return JSON.parse(body) as unknown;
  } finally {
    await reader.cancel().catch(() => undefined);
    reader.releaseLock();
  }
}

export function parseSession(value: unknown, expected: SessionRequest): SessionResponse {
  if (!value || typeof value !== 'object') throw new Error('The local API returned an invalid session.');
  const object = value as Record<string, unknown>;
  const textFields = ['url', 'token', 'room', 'identity', 'agent_name'] as const;
  if (textFields.some((field) => typeof object[field] !== 'string' || !object[field])) {
    throw new Error('The local API returned an invalid session.');
  }
  const url = new URL(object.url as string);
  if (!['ws:', 'wss:'].includes(url.protocol) || url.username || url.password) {
    throw new Error('The local API returned an unsupported transport URL.');
  }
  if (object.room !== expected.room || object.identity !== expected.identity
      || typeof object.expires_in !== 'number' || !Number.isInteger(object.expires_in)
      || object.expires_in < 1 || object.expires_in > 300
      || typeof object.agent_dispatched !== 'boolean') {
    throw new Error('The local API returned mismatched session details.');
  }
  return object as unknown as SessionResponse;
}

export async function requestSession(
  request: SessionRequest, accessToken: string, signal: AbortSignal, fetcher: typeof fetch = fetch,
): Promise<SessionResponse> {
  validateSession(request, accessToken);
  const response = await fetcher('/api/session', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${accessToken}` },
    body: JSON.stringify(request),
    signal,
    cache: 'no-store',
    credentials: 'omit',
  });
  if (!response.ok) {
    // Never echo a server body: it can contain implementation details or credentials.
    if ([401, 403].includes(response.status)) throw new Error('Local access was denied. Check the access token.');
    if (response.status === 429) throw new Error('The local session limit was reached. Try again shortly.');
    if (response.status === 422) throw new Error('The local API rejected the room or participant details.');
    throw new Error('The local API could not create a session. Check stack readiness.');
  }
  return parseSession(await boundedResponse(response), request);
}

export class LabController {
  private room: RoomPort | undefined;
  private pending: AbortController | undefined;
  private generation = 0;
  private currentState: LabState = 'disconnected';
  private microphone = false;

  constructor(
    private readonly factory: (callbacks: RoomCallbacks) => RoomPort,
    private readonly callbacks: LabCallbacks,
    private readonly fetcher: typeof fetch = fetch,
  ) {}

  get state(): LabState { return this.currentState; }

  private setState(state: LabState): void {
    this.currentState = state;
    this.callbacks.onState(state);
  }

  async connect(request: SessionRequest, accessToken: string): Promise<boolean> {
    if (['connecting', 'connected', 'reconnecting', 'disconnecting'].includes(this.currentState)) return false;
    validateSession(request, accessToken);
    const generation = ++this.generation;
    const pending = new AbortController();
    this.pending = pending;
    const timeout = setTimeout(() => pending.abort(), 15_000);
    this.setState('connecting');
    let created: RoomPort | undefined;
    try {
      const session = await requestSession(request, accessToken, pending.signal, this.fetcher);
      if (generation !== this.generation) return false;
      created = this.factory({
        onText: (text) => { if (generation === this.generation) this.callbacks.onEntry('received', text); },
        onDiagnostic: (text) => { if (generation === this.generation) this.callbacks.onEntry('diagnostic', text); },
        onReconnecting: () => {
          if (generation === this.generation && this.currentState === 'connected') this.setState('reconnecting');
        },
        onReconnected: () => {
          if (generation === this.generation && this.currentState === 'reconnecting') this.setState('connected');
        },
        onDisconnected: () => {
          if (generation !== this.generation) return;
          ++this.generation;
          this.pending?.abort();
          this.pending = undefined;
          this.room = undefined;
          this.microphone = false;
          this.callbacks.onMicrophone(false);
          this.setState('disconnected');
          this.callbacks.onEntry('system', 'The room disconnected. Reconnect with a new local session.');
        },
      });
      this.room = created;
      await created.connect(session.url, session.token);
      if (generation !== this.generation) { await created.disconnect(); return false; }
      this.setState('connected');
      this.callbacks.onEntry('system', `Joined ${session.room}. Deterministic transport agent requested.`);
      return true;
    } catch (error) {
      if (this.room === created) this.room = undefined;
      await created?.disconnect().catch(() => undefined);
      if (generation === this.generation) {
        this.setState('error');
        const safe = error instanceof LabInputError ? error.message
          : error instanceof Error && error.message.startsWith('Local access') ? error.message
          : 'Connection failed. Check local stack readiness and media networking, then reconnect.';
        this.callbacks.onEntry('error', safe);
      }
      return false;
    } finally {
      clearTimeout(timeout);
      if (this.pending === pending) this.pending = undefined;
    }
  }

  async disconnect(): Promise<void> {
    ++this.generation;
    this.pending?.abort();
    this.pending = undefined;
    const room = this.room;
    this.room = undefined;
    this.setState('disconnecting');
    try { await room?.disconnect(); }
    finally {
      this.microphone = false;
      this.callbacks.onMicrophone(false);
      this.setState('disconnected');
    }
  }

  async send(input: string): Promise<void> {
    if (!this.room || this.currentState !== 'connected') throw new LabInputError('Connect to the room first.');
    const text = validateMessage(input);
    await this.room.sendText(text);
    this.callbacks.onEntry('sent', text);
  }

  async toggleMicrophone(): Promise<void> {
    const room = this.room;
    if (!room || this.currentState !== 'connected') throw new LabInputError('Connect to the room first.');
    const next = !this.microphone;
    await room.setMicrophoneEnabled(next);
    if (room !== this.room) return;
    this.microphone = next;
    this.callbacks.onMicrophone(next);
    this.callbacks.onEntry('system', next ? 'Microphone publishing enabled by you.' : 'Microphone publishing stopped.');
  }
}
